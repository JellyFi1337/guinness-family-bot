    async def test_self_approve_and_status_split(self) -> None:
        accepted = await self._accepted(cash=150)
        item = await create_from_accepted_report(self.staff, GUILD_ID, accepted.id)
        payee_as_staff = _actor(
            user_id=USER_A, roles=self.staff.roles, guild=self.guild
        )
        with self.assertRaises(TreasuryError) as raised:
            await approve_obligation(payee_as_staff, GUILD_ID, item.id)
        self.assertEqual(raised.exception.code, "TREASURY.SELF_APPROVE")
        approved = await approve_obligation(self.reviewer, GUILD_ID, item.id)
        self.assertEqual(approved.status, "approved")
        with self.assertRaises(TreasuryError) as pay_error:
            await mark_paid(payee_as_staff, GUILD_ID, approved.id, proof_ref="screen-1")
        self.assertEqual(pay_error.exception.code, "TREASURY.SELF_PAY")
        paid = await mark_paid(self.payer, GUILD_ID, approved.id, proof_ref="screen-1")
        self.assertEqual(paid.status, "paid")
        self.assertEqual(paid.proof_ref, "screen-1")
        account = await find_account(
            family_id=paid.family_id, currency="game_money", context="memphis"
        )
        assert account is not None
        self.assertEqual(await book_balance(account.id), -150)
        confirmed = await confirm_obligation(self.alpha, GUILD_ID, paid.id)
        self.assertEqual(confirmed.confirmed_by, USER_A)

    async def test_large_payout_needs_second_decision(self) -> None:
        accepted = await self._accepted(cash=500)
        item = await create_from_accepted_report(self.staff, GUILD_ID, accepted.id)
        await get_registry().set(
            GUILD_ID, "TREASURY_BATCH_THRESHOLD", 100, updated_by="leader"
        )
        first = await approve_obligation(self.reviewer, GUILD_ID, item.id)
        self.assertEqual(first.status, "promised")
        self.assertEqual(first.approved_by, REVIEWER_ID)
        with self.assertRaises(TreasuryError) as raised:
            await approve_obligation(self.reviewer, GUILD_ID, first.id)
        self.assertEqual(raised.exception.code, "TREASURY.SECOND_REQUIRED")
        second = await approve_obligation(self.staff, GUILD_ID, first.id)
        self.assertEqual(second.status, "approved")
        self.assertEqual(second.second_approved_by, STAFF_ID)

