    async def test_reconciliation_records_discrepancy(self) -> None:
        await ensure_family_accounts(GUILD_ID)
        cards = await list_live_accounts(self.staff, GUILD_ID)
        account = next(card.account for card in cards if card.account.currency == "game_money")
        recon = await reconcile_account(
            self.payer,
            GUILD_ID,
            account.id,
            game_balance=250,
            explanation="в кассе больше, чем в книге",
        )
        self.assertEqual(recon.game_balance, 250)
        self.assertEqual(recon.book_balance, 0)
        self.assertEqual(recon.delta, 250)
        self.assertIs(type(recon.delta), int)
        refreshed = await list_live_accounts(self.staff, GUILD_ID)
        shown = next(card for card in refreshed if card.account.id == account.id)
        assert shown.last_reconciliation is not None
        self.assertEqual(shown.last_reconciliation.delta, 250)

    async def test_reverse_does_not_edit_original_entry(self) -> None:
        accepted = await self._accepted(cash=80)
        item = await create_from_accepted_report(self.staff, GUILD_ID, accepted.id)
        approved = await approve_obligation(self.reviewer, GUILD_ID, item.id)
        paid = await mark_paid(self.payer, GUILD_ID, approved.id, proof_ref="proof")
        account = await find_account(
            family_id=paid.family_id, currency="game_money", context="memphis"
        )
        assert account is not None
        entries = await list_ledger(account.id)
        self.assertEqual(len(entries), 1)
        original = entries[0]
        reversed_row = await reverse_ledger(
            self.payer, GUILD_ID, original.id, reason="ошибка перевода"
        )
        stored = await get_ledger_entry(original.id)
        assert stored is not None
        self.assertEqual(stored.amount, original.amount)
        self.assertEqual(stored.operation, "debit")
        self.assertEqual(reversed_row.operation, "reverse")
        self.assertEqual(reversed_row.reversal_of, original.id)
        self.assertEqual(await book_balance(account.id), 0)

