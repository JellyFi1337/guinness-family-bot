def _role(role_id: int, name: str) -> SimpleNamespace:
    return SimpleNamespace(id=role_id, name=name)


def _guild(roles: list[SimpleNamespace], guild_id: int = GUILD_ID) -> SimpleNamespace:
    by_id = {role.id: role for role in roles}

    def get_role(role_id: int):
        return by_id.get(int(role_id))

    return SimpleNamespace(id=guild_id, roles=roles, get_role=get_role)


def _actor(
    *,
    user_id: int,
    roles: list[SimpleNamespace],
    guild: SimpleNamespace,
    display_name: str = "officer",
) -> SimpleNamespace:
    return SimpleNamespace(
        id=user_id,
        name=display_name,
        display_name=display_name,
        roles=roles,
        guild=guild,
        guild_id=guild.id,
    )


class TreasurySchemaTests(unittest.TestCase):
    def test_migration_44_translates_to_postgresql(self) -> None:
        migration = next(item for item in MIGRATIONS if item.version == 44)
        joined = "\n".join(
            translate_sql(statement, include_returning=False)
            for statement in migration.statements
        )
        self.assertNotIn("AUTOINCREMENT", joined)
        self.assertNotIn("?", joined)
        self.assertIn("BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", joined)
        self.assertIn("accounts", joined)
        self.assertIn("ledger_entries", joined)
        self.assertIn("obligations", joined)
        self.assertIn("account_reconciliations", joined)

    def test_new_modules_have_no_float_and_no_vzp(self) -> None:
        for path in TREASURY_SOURCES:
            source = path.read_text(encoding="utf-8")
            self.assertNotIn("VZP", source)
            self.assertNotIn("ВЗП", source)
            tree = ast.parse(source)
            for node in ast.walk(tree):
                if isinstance(node, ast.Constant) and isinstance(node.value, float):
                    self.fail(f"float literal in {path}: {node.value}")
                if (
                    isinstance(node, ast.Call)
                    and isinstance(node.func, ast.Name)
                    and node.func.id == "float"
                ):
                    self.fail(f"float() in {path}")


