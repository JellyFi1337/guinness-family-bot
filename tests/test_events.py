    async def test_roster_of_50_paginates(self) -> None:
        await self._enable("territory_control")
        start, end = _window()
        event = await create_event(
            self.staff,
            GUILD_ID,
            "capt_mansion",
            starts_at=start,
            ends_at=end,
            meetup="офис организации",
            reserve_capacity=5,
        )
        self.assertEqual(event.capacity, 50)
        family_id = event.family_id
        for index in range(50):
            discord_id = 1_000_000_000_000_000_000 + index
            await add_member(
                guild_id=GUILD_ID,
                family_id=family_id,
                discord_id=discord_id,
                ic_name=f"Боец{index:02d}",
                actor_id=STAFF_ID,
                actor_name="Staff",
                status="active",
            )
            actor = _actor(
                user_id=discord_id,
                roles=list(self.alpha.roles),
                guild=self.guild,
                display_name=f"F{index:02d}",
            )
            result = await join_event(actor, GUILD_ID, event.id)
            self.assertEqual(result.seat.slot, "main")
        seats = await list_roster(event.id)
        self.assertEqual(len(seats), 50)
        lines = await roster_lines(event)
        self.assertEqual(len(lines), 50)
        pages = paginate_lines(list(lines))
        self.assertGreater(len(pages), 1)
        pager = Paginator(
            domain="events",
            object_id=str(event.id),
            lines=lines,
            title="Состав события",
        )
        self.assertGreater(len(pager.pages), 1)
        extra = _actor(
            user_id=USER_A, roles=list(self.alpha.roles), guild=self.guild
        )
        reserved = await join_event(extra, GUILD_ID, event.id)
        self.assertEqual(reserved.seat.slot, "reserve")

    async def test_cancel_reschedule_and_commander(self) -> None:
        start, end = _window()
        event = await create_event(
            self.staff,
            GUILD_ID,
            "meeting",
            starts_at=start,
            ends_at=end,
            meetup="офис организации",
            capacity=6,
        )
        moved_start, moved_end = _window(hours=8)
        moved = await reschedule_event(
            self.staff,
            GUILD_ID,
            event.id,
            starts_at=moved_start,
            ends_at=moved_end,
        )
        self.assertEqual(moved.starts_at, datetime.fromisoformat(moved_start).isoformat())
        swapped = await replace_commander(
            self.staff, GUILD_ID, event.id, USER_A
        )
        self.assertEqual(swapped.commander_id, USER_A)
        cancelled = await cancel_event(self.staff, GUILD_ID, event.id)
        self.assertEqual(cancelled.status, "cancelled")
        with self.assertRaises(EventError) as raised:
            await join_event(self.alpha, GUILD_ID, event.id)
        self.assertEqual(raised.exception.code, "EVENTS.CANCELLED")

