    async def test_idempotent_create_and_join(self) -> None:
        start, end = _window()
        first = await create_event(
            self.staff,
            GUILD_ID,
            "meeting",
            starts_at=start,
            ends_at=end,
            meetup="офис организации",
            capacity=3,
        )
        second = await create_event(
            self.staff,
            GUILD_ID,
            "meeting",
            starts_at=start,
            ends_at=end,
            meetup="другое место",
            capacity=3,
        )
        self.assertEqual(first.id, second.id)
        one = await join_event(self.alpha, GUILD_ID, first.id)
        two = await join_event(self.alpha, GUILD_ID, first.id)
        self.assertEqual(one.seat.id, two.seat.id)
        self.assertEqual(len(await list_roster(first.id)), 1)
        stored = await get_event(first.id)
        assert stored is not None
        self.assertEqual(stored.meetup, "офис организации")

