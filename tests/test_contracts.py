GUILD_ID = 5_100
FAMILY_ROLE_ID = 76
PERM_ROLE_ID = 77
STAFF_ID = 900
USER_A = 2_001
USER_B = 2_002
USER_C = 2_003


def _role(role_id: int, name: str) -> SimpleNamespace:
    return SimpleNamespace(id=role_id, name=name)


def _guild(roles: list[SimpleNamespace], guild_id: int = GUILD_ID) -> SimpleNamespace:
    by_id = {role.id: role for role in roles}

    def get_role(role_id: int):
        return by_id.get(int(role_id))

    return SimpleNamespace(id=guild_id, roles=roles, get_role=get_role)


def _actor(
    *,
    user_id: int,
    roles: list[SimpleNamespace],
    guild: SimpleNamespace,
    display_name: str = "officer",
) -> SimpleNamespace:
    return SimpleNamespace(
        id=user_id,
        name=display_name,
        display_name=display_name,
        roles=roles,
        guild=guild,
        guild_id=guild.id,
    )


class ContractSchemaTests(unittest.TestCase):
    def test_migration_translates_to_postgresql(self) -> None:
        migration = next(item for item in MIGRATIONS if item.version == 38)
        translated = [
            translate_sql(statement, include_returning=False)
            for statement in migration.statements
        ]
        joined = "\n".join(translated)
        self.assertNotIn("AUTOINCREMENT", joined)
        self.assertNotIn("?", joined)
        self.assertIn("BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", joined)
        self.assertIn("idx_contract_runs_family", joined)
        insert = translate_sql(
            """INSERT INTO contract_runs (
                   guild_id, family_id, catalog_id, snapshot_json,
                   responsible_discord_id, status, issued_resources,
                   started_at, finished_at, version, created_at, updated_at
               ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, NULL, 1, ?, ?)"""
        )
        self.assertIn("%s", insert)
        self.assertIn("RETURNING id", insert)


class ContractTests(unittest.IsolatedAsyncioTestCase):
    async def asyncSetUp(self) -> None:
        await database.close_db()
        self.temp_dir = tempfile.TemporaryDirectory()
        self.path_patch = patch.object(
            database,
            "DB_PATH",
            Path(self.temp_dir.name) / "contracts.db",
        )
        self.path_patch.start()
        await database.init_db()
        reset_obligation_sources()
        ensure_default_integrations()
        family = _role(FAMILY_ROLE_ID, "High")
        perms = _role(PERM_ROLE_ID, "Кадровик")
        self.guild = _guild([family, perms])
        self.staff = _actor(
            user_id=STAFF_ID, roles=[family, perms], guild=self.guild
        )
        self.alpha = _actor(
            user_id=USER_A, roles=[family, perms], guild=self.guild, display_name="A"
        )
        self.beta = _actor(
            user_id=USER_B, roles=[family, perms], guild=self.guild, display_name="B"
        )
        self.gamma = _actor(
            user_id=USER_C, roles=[family, perms], guild=self.guild, display_name="C"
        )
        await grant_role_permission(GUILD_ID, Permission.MEMBERS_MANAGE, PERM_ROLE_ID)
        await grant_role_permission(GUILD_ID, Permission.MEMBERS_VIEW, PERM_ROLE_ID)
        await grant_role_permission(GUILD_ID, Permission.CONTRACTS_MANAGE, PERM_ROLE_ID)
        for user_id, actor in (
            (USER_A, self.alpha),
            (USER_B, self.beta),
            (USER_C, self.gamma),
        ):
            await register_member(
                self.staff, GUILD_ID, discord_id=user_id, ic_name=f"IC{user_id}"
            )
            await verify_in_game(self.staff, GUILD_ID, user_id)
            del actor

    async def asyncTearDown(self) -> None:
        reset_obligation_sources()
        await database.close_db()
        self.path_patch.stop()
        self.temp_dir.cleanup()

    async def _published(
        self,
        *,
        title: str = "Доставка",
        upgrades: str | None = "air_cargo",
        team_max: int = 2,
        reward: str | None = None,
    ):
        item = await add_catalog_item(
            self.staff,
            GUILD_ID,
            title=title,
            direction="criminal",
            team_max=team_max,
            upgrades=upgrades,
            resources="фургон, топливо",
            reward_note=reward,
        )
        return await change_catalog_status(
            self.staff, GUILD_ID, item.id, "available"
        )

    async def test_start_freezes_catalog_snapshot(self) -> None:
        await set_guild_setting(GUILD_ID, "profile.enabled_upgrades", "air_cargo")
        item = await self._published(title="Доставка", team_max=2)
        run = await start_run(self.alpha, GUILD_ID, item.id, share_bps=4000)
        await edit_catalog_item(
            self.staff,
            GUILD_ID,
            item.id,
            title="Другое имя",
            team_max=8,
        )
        fresh_catalog = await get_catalog_item(item.id)
        assert fresh_catalog is not None
        self.assertEqual(fresh_catalog.title, "Другое имя")
        self.assertEqual(fresh_catalog.team_max, 8)
        stored = await get_run(run.id)
        assert stored is not None
        self.assertEqual(stored.snapshot["title"], "Доставка")
        self.assertEqual(stored.snapshot["team_max"], 2)
        self.assertEqual(stored.snapshot["required_upgrades"], ["air_cargo"])

    async def test_cannot_start_without_required_upgrade(self) -> None:
        item = await self._published(upgrades="air_cargo")
        row = await catalog_availability(GUILD_ID, item)
        self.assertFalse(row.startable)
        self.assertIn("air_cargo", row.reason or "")
        with self.assertRaises(ContractError) as raised:
            await start_run(self.alpha, GUILD_ID, item.id)
        self.assertEqual(raised.exception.code, "CONTRACTS.UNAVAILABLE")

    async def test_lifecycle_allows_only_legal_transitions(self) -> None:
        await set_guild_setting(GUILD_ID, "profile.enabled_upgrades", "air_cargo")
        item = await self._published(team_max=1)
        run = await start_run(self.alpha, GUILD_ID, item.id)
        self.assertEqual(run.status, "in_work")
        with self.assertRaises(ContractError) as raised:
            await transition_run(self.staff, GUILD_ID, run.id, "accepted")
        self.assertEqual(raised.exception.code, "CONTRACTS.BAD_TRANSITION")
        submitted = await transition_run(
            self.staff, GUILD_ID, run.id, "report_submitted"
        )
        self.assertEqual(submitted.status, "report_submitted")
        rework = await transition_run(self.staff, GUILD_ID, submitted.id, "rework")
        self.assertEqual(rework.status, "rework")
        again = await transition_run(self.staff, GUILD_ID, rework.id, "in_work")
        accepted = await transition_run(
            self.staff,
            GUILD_ID,
            (
                await transition_run(
                    self.staff, GUILD_ID, again.id, "report_submitted"
                )
            ).id,
            "accepted",
        )
        closed = await transition_run(self.staff, GUILD_ID, accepted.id, "closed")
        self.assertEqual(closed.status, "closed")
        with self.assertRaises(ContractError):
            await transition_run(self.staff, GUILD_ID, closed.id, "in_work")
        other = await start_run(
            self.beta,
            GUILD_ID,
            (await self._published(title="Второй", team_max=1)).id,
        )
        cancelled = await transition_run(
            self.staff, GUILD_ID, other.id, "cancelled"
        )
        self.assertEqual(cancelled.status, "cancelled")
        self.assertNotEqual(cancelled.status, "rejected")
        partial_src = await start_run(
            self.gamma,
            GUILD_ID,
            (await self._published(title="Третий", team_max=1)).id,
        )
        partial = await transition_run(
            self.staff, GUILD_ID, partial_src.id, "partial"
        )
        self.assertEqual(partial.status, "partial")

    async def test_parallel_join_does_not_exceed_team(self) -> None:
        await set_guild_setting(GUILD_ID, "profile.enabled_upgrades", "air_cargo")
        item = await self._published(team_max=2)
        run = await start_run(self.alpha, GUILD_ID, item.id, share_bps=4000)

        async def _join(actor: SimpleNamespace) -> str:
            try:
                await take_run(actor, GUILD_ID, run.id, share_bps=3000)
                return "ok"
            except ContractError as exc:
                return exc.code

        first, second = await asyncio.gather(
            _join(self.beta), _join(self.gamma)
        )
        self.assertEqual({first, second}, {"ok", "CONTRACTS.TEAM_FULL"})
        stored = await get_run(run.id)
        assert stored is not None
        self.assertEqual(len(stored.participants), 2)
        self.assertLessEqual(sum(item.share_bps for item in stored.participants), 10_000)

    async def test_shares_cannot_claim_full_revenue_twice(self) -> None:
        await set_guild_setting(GUILD_ID, "profile.enabled_upgrades", "air_cargo")
        item = await self._published(team_max=2)
        run = await start_run(self.alpha, GUILD_ID, item.id, share_bps=7000)
        with self.assertRaises(ContractError) as raised:
            await take_run(self.beta, GUILD_ID, run.id, share_bps=4000)
        self.assertEqual(raised.exception.code, "CONTRACTS.SHARE_EXCEEDED")
        joined = await take_run(self.beta, GUILD_ID, run.id, share_bps=3000)
        self.assertEqual(len(joined.participants), 2)

    async def test_leftovers_and_panel_read_open_runs(self) -> None:
        await set_guild_setting(GUILD_ID, "profile.enabled_upgrades", "air_cargo")
        item = await self._published(reward="проверка состава")
        run = await start_run(self.alpha, GUILD_ID, item.id, share_bps=5000)
        leftovers = await list_open_obligations(GUILD_ID, USER_A)
        self.assertTrue(any(item.kind == "contract" for item in leftovers))
        self.assertTrue(any(item.subject_id == str(run.id) for item in leftovers))
        panel = await build_member_panel(GUILD_ID, USER_A)
        tasks = panel.section(SECTION_TASKS)
        self.assertFalse(tasks.empty)
        public = await build_public_panel(GUILD_ID)
        text = " ".join(f"{key} {value}" for key, value in public.details)
        self.assertIn("Доставка", text)
        self.assertIn("проверка состава", text)
        self.assertIn("Инструкции", text)
        self.assertNotIn("<@", text)
        self.assertIn("Тема:", " ".join(tasks.lines))
        self.assertIn("Источник:", " ".join(tasks.lines))
        mine = await my_runs(self.alpha, GUILD_ID)
        self.assertEqual(mine[0].id, run.id)
