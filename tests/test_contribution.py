def _role(role_id: int, name: str) -> SimpleNamespace:
    return SimpleNamespace(id=role_id, name=name)


def _guild(roles: list[SimpleNamespace], guild_id: int = GUILD_ID) -> SimpleNamespace:
    by_id = {role.id: role for role in roles}

    def get_role(role_id: int):
        return by_id.get(int(role_id))

    return SimpleNamespace(id=guild_id, roles=roles, get_role=get_role, members=[])


def _actor(
    *,
    user_id: int,
    roles: list[SimpleNamespace],
    guild: SimpleNamespace,
    display_name: str = "officer",
) -> SimpleNamespace:
    return SimpleNamespace(
        id=user_id,
        name=display_name,
        display_name=display_name,
        roles=roles,
        guild=guild,
        guild_id=guild.id,
    )


class ContributionSchemaTests(unittest.TestCase):
    def test_migration_45_translates_to_postgresql(self) -> None:
        migration = next(item for item in MIGRATIONS if item.version == 45)
        joined = "\n".join(
            translate_sql(statement, include_returning=False)
            for statement in migration.statements
        )
        self.assertNotIn("AUTOINCREMENT", joined)
        self.assertNotIn("?", joined)
        self.assertIn("contribution_rule_versions", joined)
        self.assertIn("contribution_entries", joined)
        self.assertIn("BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", joined)

    def test_unit_is_zaslugi_and_modules_have_no_float_or_transfer(self) -> None:
        self.assertEqual(UNIT_NAME, "заслуги")
        import services.contribution as module

        names = {name for name, _ in inspect.getmembers(module, inspect.isfunction)}
        self.assertNotIn("transfer", names)
        self.assertNotIn("pay_member", names)
        self.assertNotIn("award_from_message", names)
        self.assertNotIn("award_from_voice", names)
        for path in SOURCES:
            source = path.read_text(encoding="utf-8")
            self.assertNotIn("VZP", source)
            self.assertNotIn("ВЗП", source)
            self.assertNotIn("Dark Coins", source)
            self.assertNotIn("def transfer", source)
            tree = ast.parse(source)
            for node in ast.walk(tree):
                if isinstance(node, ast.Constant) and isinstance(node.value, float):
                    self.fail(f"float literal in {path}: {node.value}")
                if (
                    isinstance(node, ast.Call)
                    and isinstance(node.func, ast.Name)
                    and node.func.id == "float"
                ):
                    self.fail(f"float() in {path}")


class ContributionTests(unittest.IsolatedAsyncioTestCase):
    async def asyncSetUp(self) -> None:
        await database.close_db()
        self.temp_dir = tempfile.TemporaryDirectory()
        self.path_patch = patch.object(
            database,
            "DB_PATH",
            Path(self.temp_dir.name) / "contribution.db",
        )
        self.path_patch.start()
        await database.init_db()
        reset_obligation_sources()
        ensure_report_integrations()
        ensure_event_integrations()
        family = _role(FAMILY_ROLE_ID, "High")
        perms = _role(PERM_ROLE_ID, "Кадровик")
        self.guild = _guild([family, perms])
        self.staff = _actor(user_id=STAFF_ID, roles=[family, perms], guild=self.guild)
        self.mentor = _actor(
            user_id=MENTOR_ID, roles=[family, perms], guild=self.guild, display_name="M"
        )
        self.alpha = _actor(
            user_id=USER_A, roles=[family], guild=self.guild, display_name="A"
        )
        self.beta = _actor(
            user_id=USER_B, roles=[family], guild=self.guild, display_name="B"
        )
        for permission in (
            Permission.MEMBERS_MANAGE,
            Permission.MEMBERS_VIEW,
            Permission.CONTRACTS_MANAGE,
            Permission.REPORTS_REVIEW,
            Permission.EVENTS_CREATE,
            Permission.EVENTS_MANAGE_OWN,
            Permission.EVENTS_MANAGE_ALL,
            Permission.APPLICATIONS_REVIEW,
            Permission.TRAINING_MANAGE,
        ):
            await grant_role_permission(GUILD_ID, permission, PERM_ROLE_ID)
        await set_guild_setting(GUILD_ID, "profile.enabled_upgrades", "air_cargo")
        await register_member(self.staff, GUILD_ID, discord_id=STAFF_ID, ic_name="Staff")
        await register_member(self.staff, GUILD_ID, discord_id=MENTOR_ID, ic_name="Mentor")
        await verify_in_game(self.staff, GUILD_ID, MENTOR_ID)
        await register_member(self.staff, GUILD_ID, discord_id=USER_A, ic_name="ICA")
        await verify_in_game(self.staff, GUILD_ID, USER_A)

    async def asyncTearDown(self) -> None:
        reset_obligation_sources()
        await database.close_db()
        self.path_patch.stop()
        self.temp_dir.cleanup()

    async def _rules(self, **amounts: int):
        payload = {
            "contract": 0,
            "attendance": 0,
            "mentoring": 0,
            "warehouse": 0,
            "logistics": 0,
            "duty": 0,
        }
        payload.update(amounts)
        return await publish_rules(self.staff, GUILD_ID, payload)

    async def _accepted_report(self, *, title: str = "Доставка"):
        item = await add_catalog_item(
            self.staff,
            GUILD_ID,
            title=title,
            direction="criminal",
            team_max=1,
            upgrades="air_cargo",
        )
        published = await change_catalog_status(
            self.staff, GUILD_ID, item.id, "available"
        )
        run = await start_run(self.alpha, GUILD_ID, published.id)
        report = await submit_report(
            self.alpha,
            GUILD_ID,
            run.id,
            result_amount=40,
            shares=f"{USER_A}:40",
            duration_minutes=15,
            links="https://example.com/shot.png",
            cash=40,
        )
        return await review_report(
            self.staff, GUILD_ID, report.id, "accept", reason="принято"
        )

    async def test_unaccepted_report_does_not_award(self) -> None:
        await self._rules(contract=6)
        item = await add_catalog_item(
            self.staff,
            GUILD_ID,
            title="Черновик",
            direction="criminal",
            team_max=1,
            upgrades="air_cargo",
        )
        published = await change_catalog_status(
            self.staff, GUILD_ID, item.id, "available"
        )
        run = await start_run(self.alpha, GUILD_ID, published.id)
        report = await submit_report(
            self.alpha,
            GUILD_ID,
            run.id,
            result_amount=10,
            shares=f"{USER_A}:10",
            duration_minutes=5,
            links="https://example.com/x.png",
        )
        with self.assertRaises(ContributionError) as raised:
            await award_from_accepted_report(self.staff, GUILD_ID, report.id)
        self.assertEqual(raised.exception.code, "CONTRIB.NOT_CONFIRMED")
        self.assertEqual(await member_breakdown(GUILD_ID, USER_A), {
            "contract": 0,
            "attendance": 0,
            "mentoring": 0,
            "warehouse": 0,
            "logistics": 0,
            "duty": 0,
        })

    async def test_accepted_report_awards_once_per_basis(self) -> None:
        first_rules = await self._rules(contract=6)
        accepted = await self._accepted_report()
        first = await award_from_accepted_report(self.staff, GUILD_ID, accepted.id)
        second = await award_from_accepted_report(self.staff, GUILD_ID, accepted.id)
        self.assertEqual({item.id for item in first}, {item.id for item in second})
        self.assertEqual((await member_breakdown(GUILD_ID, USER_A))["contract"], 6)
        self.assertEqual(first[0].rule_version, first_rules.version)

    async def test_rule_version_is_frozen_on_award(self) -> None:
        first_rules = await self._rules(contract=5)
        first_report = await self._accepted_report(title="Первый")
        await self._rules(contract=9)
        second_report = await self._accepted_report(title="Второй")
        first = await list_entries_for_member(first_report.family_id, USER_A)
        awards = [row for row in first if row.operation == "award"]
        self.assertEqual(len(awards), 2)
        by_basis = {row.basis_id: row for row in awards}
        self.assertEqual(by_basis[str(first_report.id)].amount, 5)
        self.assertEqual(by_basis[str(first_report.id)].rule_version, first_rules.version)
        self.assertEqual(by_basis[str(second_report.id)].amount, 9)
        self.assertEqual((await member_breakdown(GUILD_ID, USER_A))["contract"], 14)

    async def test_reverse_keeps_original_and_bonus_does_not_zero(self) -> None:
        await self._rules(contract=8)
        accepted = await self._accepted_report()
        awarded = await award_from_accepted_report(self.staff, GUILD_ID, accepted.id)
        original = awarded[0]
        reversed_row = await reverse_entry(
            self.staff, GUILD_ID, original.id, reason="ошибка сверки"
        )
        stored = await get_entry(original.id)
        assert stored is not None
        self.assertEqual(stored.amount, 8)
        self.assertEqual(stored.operation, "award")
        self.assertEqual(reversed_row.operation, "reverse")
        self.assertEqual(reversed_row.reversal_of, original.id)
        self.assertEqual((await member_breakdown(GUILD_ID, USER_A))["contract"], 0)
        await reverse_report(self.staff, GUILD_ID, accepted.id, reason="отмена отчёта")
        await self._rules(contract=8)
        second = await self._accepted_report(title="После отмены")
        await award_from_accepted_report(self.staff, GUILD_ID, second.id)
        before = await member_breakdown(GUILD_ID, USER_A)
        await acknowledge_bonus_payout(self.staff, GUILD_ID, "2026-W36")
        after = await member_breakdown(GUILD_ID, USER_A)
        self.assertEqual(before, after)
        self.assertEqual(after["contract"], 8)
        self.assertGreater(len(await list_entries_for_member(second.family_id, USER_A)), 0)

    async def test_attendance_only_when_commander_confirms(self) -> None:
        await self._rules(attendance=4)
        start = datetime.now(UTC) + timedelta(hours=2)
        end = start + timedelta(hours=2)
        event = await create_event(
            self.staff,
            GUILD_ID,
            "meeting",
            starts_at=start.isoformat(),
            ends_at=end.isoformat(),
            meetup="офис организации",
            capacity=2,
            reserve_capacity=0,
            commander_id=STAFF_ID,
        )
        await join_event(self.alpha, GUILD_ID, event.id)
        await confirm_ready(self.alpha, GUILD_ID, event.id)
        await mark_voice_hint(self.staff, GUILD_ID, event.id, USER_A)
        self.assertEqual((await member_breakdown(GUILD_ID, USER_A))["attendance"], 0)
        with self.assertRaises(ContributionError) as raised:
            await award_from_attendance(self.staff, GUILD_ID, event.id, USER_A)
        self.assertEqual(raised.exception.code, "CONTRIB.NOT_CONFIRMED")
        await confirm_attendance(self.staff, GUILD_ID, event.id, USER_A, "attended")
        self.assertEqual((await member_breakdown(GUILD_ID, USER_A))["attendance"], 4)
        await confirm_attendance(self.staff, GUILD_ID, event.id, USER_A, "no_show")
        self.assertEqual((await member_breakdown(GUILD_ID, USER_A))["attendance"], 0)

