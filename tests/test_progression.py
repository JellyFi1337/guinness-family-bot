    async def test_lore_revision_flags_templates_clearances_and_upgrades(self) -> None:
        node = await define_upgrade(
            self.staff,
            GUILD_ID,
            key="office",
            title="Офис",
            track="other",
        )
        family = await ensure_family(GUILD_ID)
        member = await get_current_member(family.id, USER_A)
        self.assertIsNotNone(member)
        assert member is not None
        await grant_clearance(
            member_id=member.id,
            activity="warehouse",
            granted_by=STAFF_ID,
        )
        _updated, flagged = await publish_lore_revision(
            self.staff, GUILD_ID, "28.07.2026"
        )
        self.assertGreaterEqual(flagged, 1 + len(EVENT_TEMPLATES))
        open_rows = await list_open_reviews(family.id, "28.07.2026")
        kinds = {item.kind for item in open_rows}
        self.assertIn("upgrade", kinds)
        self.assertIn("template", kinds)
        self.assertIn("clearance", kinds)
        self.assertTrue(any(item.subject_key == node.key for item in open_rows))
        self.assertTrue(any(item.subject_key == "warehouse" for item in open_rows))
        await mark_lore_reviewed(self.staff, GUILD_ID, "upgrade", node.key)
        reviewed = await get_lore_review(family.id, "upgrade", node.key, "28.07.2026")
        self.assertIsNotNone(reviewed)
        assert reviewed is not None
        self.assertEqual(reviewed.status, REVIEW_DONE)
        leftover = await list_open_reviews(family.id, "28.07.2026")
        self.assertFalse(any(item.subject_key == node.key for item in leftover))
        await set_goal(self.staff, GUILD_ID, node.key, note="собрать ресурс")
        announced = await announce_season(
            self.staff,
            GUILD_ID,
            season_key="season-3",
            starts_on="2026-10-28",
            ends_on="2027-01-27",
        )
        self.assertEqual(announced.influence_daily_limit, 0)
        self.assertEqual(announced.half_loss_threshold, 0)
        profile = await active_profile(GUILD_ID)
        self.assertEqual(profile.season_key, "season-3")
        self.assertEqual(profile.season_end, date(2027, 1, 27))


