    async def test_legal_and_illegal_tracks_cannot_advance_together(self) -> None:
        legal = await define_upgrade(
            self.staff,
            GUILD_ID,
            key="legal_office",
            title="Офис легальных контрактов",
            track="legal_contracts",
            cost_reputation=200,
        )
        illegal = await define_upgrade(
            self.staff,
            GUILD_ID,
            key="illegal_lab",
            title="Лаборатория",
            track="illegal_contracts",
        )
        other = await define_upgrade(
            self.staff,
            GUILD_ID,
            key="garage",
            title="Гараж",
            track="other",
        )
        await advance_upgrade(self.staff, GUILD_ID, legal.key)
        with self.assertRaises(ProgressionError) as raised:
            await advance_upgrade(self.staff, GUILD_ID, illegal.key)
        self.assertEqual(raised.exception.code, "PROG.TRACK_LOCK")
        node, progress = await advance_upgrade(self.staff, GUILD_ID, other.key)
        self.assertEqual(node.key, "garage")
        self.assertEqual(progress.current_level, 1)
        profile = await active_profile(GUILD_ID)
        self.assertFalse(profile.enabled_upgrades)

    async def test_direction_change_shows_consequences_then_resets(self) -> None:
        with self.assertRaises(ProgressionError) as preview_unset:
            await preview_direction_change(self.staff, GUILD_ID, "criminal")
        self.assertEqual(preview_unset.exception.code, "PROG.DIRECTION")
        initial = await confirm_direction_change(
            self.staff, GUILD_ID, "legal", confirm=True, expected_version=0
        )
        self.assertEqual(initial.after, "legal")
        self.assertEqual(initial.returned, 0)
        legal = await define_upgrade(
            self.staff,
            GUILD_ID,
            key="legal_office",
            title="Офис",
            track="legal_contracts",
            cost_reputation=200,
        )
        await advance_upgrade(self.staff, GUILD_ID, legal.key)
        with self.assertRaises(ProgressionError) as unconfirmed:
            await confirm_direction_change(
                self.staff, GUILD_ID, "criminal", confirm=False, expected_version=1
            )
        self.assertEqual(unconfirmed.exception.code, "PROG.CONFIRM")
        preview = await preview_direction_change(self.staff, GUILD_ID, "criminal")
        self.assertEqual(preview.spent_reputation, 200)
        self.assertEqual(preview.returned_reputation, 190)
        self.assertEqual(preview.cooldown_days, 7)
        self.assertIn("сброс", preview.summary)
        change = await confirm_direction_change(
            self.staff,
            GUILD_ID,
            "criminal",
            confirm=True,
            expected_version=preview.version,
        )
        self.assertEqual(change.after, "criminal")
        self.assertEqual(change.spent, 200)
        self.assertEqual(change.returned, 190)
        progress = await get_progress(legal.id)
        self.assertIsNotNone(progress)
        assert progress is not None
        self.assertEqual(progress.current_level, 0)
        family = await ensure_family(GUILD_ID)
        development = await get_development(family.id)
        self.assertIsNotNone(development)
        assert development is not None
        self.assertEqual(development.spent_reputation, 190)
        self.assertEqual(len(await list_progress(family.id)), 1)
        decisions = await list_decisions(GUILD_ID, action="PROG.DIRECTION")
        self.assertGreaterEqual(len(decisions), 2)
        self.assertIn("сброс", decisions[0].reason or "")
        preview_back = await preview_direction_change(self.staff, GUILD_ID, "legal")
        with self.assertRaises(ProgressionError) as cooling:
            await confirm_direction_change(
                self.staff,
                GUILD_ID,
                "legal",
                confirm=True,
                expected_version=preview_back.version,
            )
        self.assertEqual(cooling.exception.code, "PROG.COOLDOWN")

