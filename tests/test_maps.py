class MapSchemaTests(unittest.TestCase):
    def test_migration_51_translates_to_postgresql(self) -> None:
        migration = next(item for item in MIGRATIONS if item.version == 51)
        joined = "\n".join(
            translate_sql(statement, include_returning=False)
            for statement in migration.statements
        )
        self.assertNotIn("AUTOINCREMENT", joined)
        self.assertNotIn("?", joined)
        self.assertIn("family_maps", joined)
        self.assertIn("idx_family_maps_active_name", joined)
        self.assertIn("BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", joined)

    def test_active_toml_has_no_milton_maps_or_old_keys(self) -> None:
        text = (ROOT / "bot_config.toml").read_text(encoding="utf-8")
        self.assertNotIn("CHOICE_MAP", text)
        self.assertNotIn("GTA5RP_", text)
        self.assertNotIn("vzp_milton", text)
        for name in MILTON_MAP_NAMES:
            self.assertNotIn(name, text)

    def test_legacy_tokens_only_in_compatible_readers(self) -> None:
        pattern = re.compile(r"vzp_milton|CHOICE_MAP|GTA5RP_")
        hits: list[str] = []
        for path in ROOT.rglob("*"):
            if not path.is_file() or path.suffix not in {".py", ".toml"}:
                continue
            if any(part in _SKIP_DIRS for part in path.parts):
                continue
            if path.resolve() in _LEGACY_ALLOWED:
                continue
            if pattern.search(path.read_text(encoding="utf-8")):
                hits.append(str(path.relative_to(ROOT)))
        self.assertEqual(hits, [])

    def test_select_pages_more_than_discord_option_cap(self) -> None:
        maps = tuple(_fake_map(index) for index in range(1, 27))
        first, page, total = map_select_page(maps, 0)
        second, second_page, _ = map_select_page(maps, 1)
        self.assertEqual(SELECT_PAGE_SIZE, 25)
        self.assertEqual(len(first), 25)
        self.assertEqual(len(second), 1)
        self.assertEqual(page, 0)
        self.assertEqual(second_page, 1)
        self.assertEqual(total, 2)
        self.assertEqual(first[0].name, "Тестовая 1")
        self.assertEqual(second[0].name, "Тестовая 26")

    def test_catalog_ref_roundtrip(self) -> None:
        self.assertEqual(parse_catalog_ref(catalog_ref(12)), 12)
        self.assertIsNone(parse_catalog_ref("legacy/path.webp"))

    def test_choice_map_keys_warn_and_are_ignored(self) -> None:
        fake = {"CHOICE_MAP_1": ["Ветряки", "ignored.webp"]}
        with patch.object(config_module, "_SETTINGS", fake):
            with self.assertLogs("config", level="WARNING") as logs:
                found = config_module._consume_legacy_choice_maps()
        self.assertEqual(found, ("CHOICE_MAP_1",))
        self.assertTrue(any("CHOICE_MAP_1" in line for line in logs.output))

    def test_old_gta5rp_key_warns_and_new_name_wins(self) -> None:
        legacy = dict(config_module._SETTINGS)
        legacy["GTA5RP_MASTER_URL"] = "https://old.example/"
        with patch.object(config_module, "_SETTINGS", legacy):
            with self.assertLogs("config", level="WARNING") as logs:
                value = config_module._legacy_text(
                    "rage_master_url",
                    "GTA5RP_MASTER_URL",
                    "https://cdn.rage.mp/master/",
                )
        self.assertEqual(value, "https://cdn.rage.mp/master/")
        self.assertTrue(any("GTA5RP_MASTER_URL" in line for line in logs.output))


class MapCatalogTests(unittest.IsolatedAsyncioTestCase):
    async def asyncSetUp(self) -> None:
        await database.close_db()
        self.temp_dir = tempfile.TemporaryDirectory()
        self.path_patch = patch.object(
            database,
            "DB_PATH",
            Path(self.temp_dir.name) / "maps.db",
        )
        self.path_patch.start()
        await database.init_db()
        reset_obligation_sources()
        family = _role(FAMILY_ROLE_ID, "High")
        perms = _role(PERM_ROLE_ID, "Кадровик")
        self.guild = _guild([family, perms])
        self.staff = _actor(user_id=STAFF_ID, roles=[family, perms], guild=self.guild)
        for permission in (
            Permission.MEMBERS_MANAGE,
            Permission.EVENTS_CREATE,
            Permission.EVENTS_MANAGE_ALL,
        ):
            await grant_role_permission(GUILD_ID, permission, PERM_ROLE_ID)
        await register_member(
            self.staff, GUILD_ID, discord_id=STAFF_ID, ic_name="Staff"
        )

    async def asyncTearDown(self) -> None:
        reset_obligation_sources()
        await database.close_db()
        self.path_patch.stop()
        self.temp_dir.cleanup()

    async def test_empty_catalog_has_no_milton_names(self) -> None:
        items = await list_catalog(GUILD_ID)
        self.assertEqual(items, ())
        names = {item.name for item in items}
        self.assertTrue(names.isdisjoint(MILTON_MAP_NAMES))
        spec = catalog_spec(items)
        self.assertEqual(spec.code, "MAPS.EMPTY")
        for name in MILTON_MAP_NAMES:
            self.assertNotIn(name, spec.summary)

    async def test_staff_adds_and_archives_without_seeding_milton(self) -> None:
        created = await add_map(
            self.staff,
            GUILD_ID,
            name="Тестовая площадка",
            event_type="capt_square",
            version="сборка-проверки",
            source="подтверждение состава",
        )
        listed = await list_maps(self.staff, GUILD_ID)
        self.assertEqual(len(listed), 1)
        self.assertEqual(listed[0].id, created.id)
        self.assertNotIn(created.name, MILTON_MAP_NAMES)
        with self.assertRaises(MapError) as raised:
            await add_map(
                self.staff,
                GUILD_ID,
                name="Тестовая площадка",
                event_type="capt_square",
                version="сборка-проверки",
                source="подтверждение состава",
            )
        self.assertEqual(raised.exception.code, "MAPS.DUPLICATE")
        archived = await archive_map(self.staff, GUILD_ID, created.id)
        self.assertTrue(archived.archived)
        self.assertEqual(await list_catalog(GUILD_ID), ())

    async def test_empty_fields_are_rejected(self) -> None:
        with self.assertRaises(MapError) as raised:
            await add_map(
                self.staff,
                GUILD_ID,
                name="   ",
                event_type="capt_square",
                version="1",
                source="проверка",
            )
        self.assertEqual(raised.exception.code, "MAPS.REQUIRED")
        self.assertTrue(raised.exception.retryable)


