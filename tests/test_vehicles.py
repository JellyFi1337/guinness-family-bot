    async def test_property_register_does_not_duplicate_warehouse_tax(self) -> None:
        item = await upsert_property(
            self.staff,
            GUILD_ID,
            kind="office",
            title="Офис семьи",
            responsible_id=STAFF_ID,
            backup_id=USER_B,
            due_at="2026-10-01T00:00:00+00:00",
        )
        self.assertFalse(item.executed)
        paid = await execute_property(
            self.staff,
            GUILD_ID,
            kind="office",
            title="Офис семьи",
            paid_at="2026-09-20T00:00:00+00:00",
        )
        self.assertTrue(paid.executed)
        self.assertEqual(paid.last_paid_at, "2026-09-20T00:00:00+00:00")
        await upsert_property(
            self.staff,
            GUILD_ID,
            kind="warehouse",
            title="Склад",
            responsible_id=STAFF_ID,
            backup_id=USER_B,
            due_at="2026-11-01T00:00:00+00:00",
        )
        family = await ensure_family(GUILD_ID)
        self.assertEqual(await list_tax_duties(family.id), [])
