def _role(role_id: int, name: str) -> SimpleNamespace:
    return SimpleNamespace(id=role_id, name=name)


def _guild(roles: list[SimpleNamespace], guild_id: int = GUILD_ID) -> SimpleNamespace:
    by_id = {role.id: role for role in roles}

    def get_role(role_id: int):
        return by_id.get(int(role_id))

    return SimpleNamespace(id=guild_id, roles=roles, get_role=get_role, members=[])


def _actor(
    *,
    user_id: int,
    roles: list[SimpleNamespace],
    guild: SimpleNamespace,
    display_name: str = "officer",
) -> SimpleNamespace:
    return SimpleNamespace(
        id=user_id,
        name=display_name,
        display_name=display_name,
        roles=roles,
        guild=guild,
        guild_id=guild.id,
    )


class BonusMathTests(unittest.TestCase):
    def test_migration_46_translates_to_postgresql(self) -> None:
        migration = next(item for item in MIGRATIONS if item.version == 46)
        joined = "\n".join(
            translate_sql(statement, include_returning=False)
            for statement in migration.statements
        )
        self.assertNotIn("AUTOINCREMENT", joined)
        self.assertNotIn("?", joined)
        self.assertIn("bonus_periods", joined)
        self.assertIn("bonus_shares", joined)
        self.assertIn("BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", joined)

    def test_no_float_or_transfer_or_vzp(self) -> None:
        names = {name for name, _ in inspect.getmembers(
            __import__("services.bonus", fromlist=["bonus"]), inspect.isfunction
        )}
        self.assertNotIn("transfer", names)
        for path in SOURCES:
            source = path.read_text(encoding="utf-8")
            self.assertNotIn("VZP", source)
            self.assertNotIn("ВЗП", source)
            self.assertNotIn("def transfer", source)
            self.assertNotIn("cogs.fundraiser", source)
            self.assertNotIn("fundraiser_contributions", source)
            tree = ast.parse(source)
            for node in ast.walk(tree):
                if isinstance(node, ast.Constant) and isinstance(node.value, float):
                    self.fail(f"float literal in {path}: {node.value}")
                if (
                    isinstance(node, ast.Call)
                    and isinstance(node.func, ast.Name)
                    and node.func.id == "float"
                ):
                    self.fail(f"float() in {path}")

    def test_distribution_and_cap(self) -> None:
        self.assertEqual(
            distribute_amounts(100, {1: 1, 2: 1}, max_share_percent=0),
            {1: 50, 2: 50},
        )
        self.assertEqual(
            distribute_amounts(100, {1: 2, 2: 1}, max_share_percent=0),
            {1: 67, 2: 33},
        )
        self.assertEqual(
            distribute_amounts(100, {1: 10}, max_share_percent=40),
            {1: 40},
        )

    def test_rank_thresholds_at_boundaries(self) -> None:
        ranks = default_ranks()
        self.assertIsNone(resolve_rank(499, ranks))
        self.assertEqual(resolve_rank(500, ranks).name, "Чужаки")
        self.assertEqual(resolve_rank(1299, ranks).name, "Чужаки")
        self.assertEqual(resolve_rank(1300, ranks).name, "Местные")
        self.assertEqual(resolve_rank(2599, ranks).name, "Местные")
        self.assertEqual(resolve_rank(2600, ranks).name, "Авангард")
        self.assertEqual(resolve_rank(11499, ranks).name, "Империя")
        self.assertEqual(resolve_rank(11500, ranks).name, "Орден")
        self.assertEqual(resolve_rank(20000, ranks).name, "Орден")
        self.assertEqual(format_multiplier(1100), "×1,1")
        self.assertEqual(format_multiplier(1350), "×1,35")
        self.assertEqual(format_multiplier(2000), "×2")

    def test_ranks_card_does_not_promise_dark_coins(self) -> None:
        spec = ranks_card_spec(default_ranks(), 2600, resolve_rank(2600, default_ranks()))
        text = " ".join(part for _, part in spec.details) + (spec.summary or "")
        self.assertIn("не обещает", text)
        self.assertNotIn("вам начислят", text.lower())
        self.assertNotIn("получите", text.lower())


class BonusTests(unittest.IsolatedAsyncioTestCase):
    async def asyncSetUp(self) -> None:
        await database.close_db()
        self.temp_dir = tempfile.TemporaryDirectory()
        self.path_patch = patch.object(
            database,
            "DB_PATH",
            Path(self.temp_dir.name) / "bonus.db",
        )
        self.path_patch.start()
        await database.init_db()
        reset_obligation_sources()
        ensure_report_integrations()
        family = _role(FAMILY_ROLE_ID, "High")
        perms = _role(PERM_ROLE_ID, "Казна")
        self.guild = _guild([family, perms])
        self.staff = _actor(user_id=STAFF_ID, roles=[family, perms], guild=self.guild)
        self.reviewer = _actor(
            user_id=REVIEWER_ID, roles=[family, perms], guild=self.guild, display_name="R"
        )
        self.alpha = _actor(
            user_id=USER_A, roles=[family], guild=self.guild, display_name="A"
        )
        self.beta = _actor(
            user_id=USER_B, roles=[family], guild=self.guild, display_name="B"
        )
        for permission in (
            Permission.MEMBERS_MANAGE,
            Permission.MEMBERS_VIEW,
            Permission.CONTRACTS_MANAGE,
            Permission.REPORTS_REVIEW,
            Permission.TREASURY_VIEW,
            Permission.TREASURY_APPROVE,
            Permission.TREASURY_PAY,
        ):
            await grant_role_permission(GUILD_ID, permission, PERM_ROLE_ID)
        await set_guild_setting(GUILD_ID, "profile.enabled_upgrades", "air_cargo")
        await register_member(self.staff, GUILD_ID, discord_id=STAFF_ID, ic_name="Staff")
        await verify_in_game(self.staff, GUILD_ID, STAFF_ID)
        await register_member(
            self.staff, GUILD_ID, discord_id=REVIEWER_ID, ic_name="Review"
        )
        await register_member(self.staff, GUILD_ID, discord_id=USER_A, ic_name="ICA")
        await verify_in_game(self.staff, GUILD_ID, USER_A)
        await register_member(self.staff, GUILD_ID, discord_id=USER_B, ic_name="ICB")
        await verify_in_game(self.staff, GUILD_ID, USER_B)

    async def asyncTearDown(self) -> None:
        reset_obligation_sources()
        get_registry().clear_cache()
        await database.close_db()
        self.path_patch.stop()
        self.temp_dir.cleanup()

    async def _rules(self, **amounts: int):
        payload = {
            "contract": 0,
            "attendance": 0,
            "mentoring": 0,
            "warehouse": 0,
            "logistics": 0,
            "duty": 0,
        }
        payload.update(amounts)
        return await publish_rules(self.staff, GUILD_ID, payload)

    async def _accepted_report(self, actor: SimpleNamespace, *, title: str) -> None:
        item = await add_catalog_item(
            self.staff,
            GUILD_ID,
            title=title,
            direction="criminal",
            team_max=1,
            upgrades="air_cargo",
        )
        published = await change_catalog_status(
            self.staff, GUILD_ID, item.id, "available"
        )
        run = await start_run(actor, GUILD_ID, published.id)
        report = await submit_report(
            actor,
            GUILD_ID,
            run.id,
            result_amount=40,
            shares=f"{actor.id}:40",
            duration_minutes=15,
            links="https://example.com/shot.png",
            cash=40,
        )
        reviewer = self.reviewer if actor.id == STAFF_ID else self.staff
        await review_report(reviewer, GUILD_ID, report.id, "accept", reason="принято")

    async def _declare(self, *, fund: int = 100, mentor: int = 0, logistics: int = 0):
        return await declare_period(
            self.staff,
            GUILD_ID,
            period_key="2026-W36",
            fund=fund,
            mentor_fund=mentor,
            logistics_fund=logistics,
            starts_at=RANGE_START,
            ends_at=RANGE_END,
        )

    async def test_preview_splits_by_merits_and_leader_can_adjust(self) -> None:
        await self._rules(contract=2)
        await self._accepted_report(self.alpha, title="A1")
        await self._accepted_report(self.alpha, title="A2")
        await self._accepted_report(self.beta, title="B1")
        self.assertEqual((await member_breakdown(GUILD_ID, USER_A))["contract"], 4)
        self.assertEqual((await member_breakdown(GUILD_ID, USER_B))["contract"], 2)
        await self._declare(fund=100)
        bundle = await preview_period(self.staff, GUILD_ID, "2026-W36")
        by_member = {
            item.member_discord_id: item.adjusted_amount for item in bundle.shares
        }
        self.assertEqual(by_member[USER_A], 67)
        self.assertEqual(by_member[USER_B], 33)
        adjusted = await adjust_share(
            self.staff,
            GUILD_ID,
            "2026-W36",
            member_discord_id=USER_B,
            pool="combat",
            amount=40,
        )
        by_member = {
            item.member_discord_id: item.adjusted_amount for item in adjusted.shares
        }
        self.assertEqual(by_member[USER_A], 67)
        self.assertEqual(by_member[USER_B], 40)

    async def test_self_approve_forbidden_then_other_creates_obligation(self) -> None:
        await self._rules(contract=5)
        await self._accepted_report(self.alpha, title="Solo")
        await self._accepted_report(self.staff, title="StaffRun")
        await self._declare(fund=50)
        await preview_period(self.staff, GUILD_ID, "2026-W36")
        with self.assertRaises(BonusError) as raised:
            await approve_period(self.staff, GUILD_ID, "2026-W36")
        self.assertEqual(raised.exception.code, "BONUS.SELF_APPROVE")
        approved = await approve_period(self.reviewer, GUILD_ID, "2026-W36")
        self.assertEqual(approved.period.status, "approved")
        obligation = await find_obligation(
            family_id=approved.period.family_id,
            basis_kind="bonus",
            basis_id=f"2026-W36:{USER_A}",
        )
        self.assertIsNotNone(obligation)
        assert obligation is not None
        self.assertEqual(obligation.currency, "game_money")
        self.assertGreater(int(obligation.amount or 0), 0)
        again = await approve_period(self.reviewer, GUILD_ID, "2026-W36")
        self.assertEqual(again.period.id, approved.period.id)
        period, shares, categories, place = await member_view(
            self.alpha, GUILD_ID, "2026-W36"
        )
        self.assertEqual(period.status, "approved")
        self.assertEqual(categories["contract"], 5)
        self.assertGreater(place, 0)
        spec = member_card_spec(period, shares, categories, place, ())
        self.assertIn("не обещает", spec.summary or "")

    async def test_closed_period_ignores_formula_change(self) -> None:
        await self._rules(contract=10)
        await self._accepted_report(self.alpha, title="Freeze")
        await self._declare(fund=80)
        first = await preview_period(self.staff, GUILD_ID, "2026-W36")
        amount = first.shares[0].adjusted_amount
        self.assertEqual(amount, 80)
        frozen_version = first.period.rule_version
        approved = await approve_period(self.staff, GUILD_ID, "2026-W36")
        await self._rules(contract=1)
        await get_registry().set(
            GUILD_ID, "BONUS_MIN_POINTS", 999, updated_by="leader"
        )
        await self._accepted_report(self.beta, title="AfterClose")
        shown = await preview_period(self.staff, GUILD_ID, "2026-W36")
        self.assertEqual(shown.period.status, "approved")
        self.assertEqual(shown.period.rule_version, frozen_version)
        self.assertEqual(shown.shares[0].adjusted_amount, amount)
        self.assertEqual(len(shown.shares), 1)
        with self.assertRaises(BonusError) as raised:
            await declare_period(
                self.staff,
                GUILD_ID,
                period_key="2026-W36",
                fund=1,
                starts_at=RANGE_START,
                ends_at=RANGE_END,
            )
        self.assertEqual(raised.exception.code, "BONUS.CLOSED")
        shown_again = await show_period(self.staff, GUILD_ID, "2026-W36")
        self.assertEqual(shown_again.period.id, approved.period.id)

    async def test_min_threshold_and_influence_unset(self) -> None:
        await self._rules(contract=4)
        await self._accepted_report(self.alpha, title="Low")
        await self._accepted_report(self.beta, title="High1")
        await self._accepted_report(self.beta, title="High2")
        await get_registry().set(GUILD_ID, "BONUS_MIN_POINTS", 5, updated_by="leader")
        await self._declare(fund=90)
        bundle = await preview_period(self.staff, GUILD_ID, "2026-W36")
        members = {item.member_discord_id for item in bundle.shares}
        self.assertNotIn(USER_A, members)
        self.assertIn(USER_B, members)
        self.assertEqual(bundle.shares[0].adjusted_amount, 90)
        ranks, influence, current = await ranks_view(GUILD_ID)
        self.assertGreater(len(ranks), 0)
        self.assertIsNone(influence)
        self.assertIsNone(current)
