    async def test_429_returns_stale_snapshot_not_zero(self) -> None:
        await self._fill_ready()
        await upsert_external_snapshot(
            GUILD_ID,
            SOURCE_MAJESTIC_API,
            RESOURCE_ONLINE,
            '{"players":185}',
            "2026-09-09T08:15:00+00:00",
            "Источник: Majestic RP",
        )
        session = FakeSession([_FakeResponse(429, headers={"Retry-After": "1"})] * 4)
        sleeper = AsyncMock()
        client = MajesticApiClient(session=session, sleeper=sleeper, api_key=FAKE_KEY)
        with self.assertLogs("services.external.majestic_api", level="WARNING") as logs:
            snapshot = await client.fetch_online(GUILD_ID)
        self.assertTrue(snapshot.stale)
        self.assertEqual(snapshot.players(), 185)
        self.assertIsNotNone(snapshot.fetched_at)
        self.assertNotEqual(snapshot.players(), 0)
        self.assertGreaterEqual(sleeper.await_count, 1)
        joined = "\n".join(logs.output)
        self.assertNotIn(FAKE_KEY, joined)
        headers = session.calls[0]["headers"]
        self.assertIsInstance(headers, dict)
        assert isinstance(headers, dict)
        self.assertEqual(headers[API_KEY_HEADER], FAKE_KEY)

