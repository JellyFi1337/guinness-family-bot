    async def test_rating_periods_store_separately(self) -> None:
        await self._fill_ready()
        session = FakeSession(
            [
                _FakeResponse(200, {"name": "Guinness", "place": 3, "influence": 500}),
                _FakeResponse(200, {"name": "Guinness", "place": 1, "influence": 900}),
            ]
        )
        client = MajesticApiClient(
            session=session, sleeper=AsyncMock(), api_key=FAKE_KEY
        )
        week = await client.fetch_org_rating(GUILD_ID, "week")
        season = await client.fetch_org_rating(GUILD_ID, "season")
        self.assertEqual(week.resource, "rating-organizations/week")
        self.assertEqual(season.resource, "rating-organizations/season")
        self.assertTrue(str(session.calls[0]["url"]).endswith("/rating-organizations"))
        self.assertEqual(session.calls[0]["params"]["period"], "week")
        self.assertEqual(session.calls[1]["params"]["period"], "season")
        stored_week = await get_external_snapshot(
            GUILD_ID, SOURCE_MAJESTIC_API, "rating-organizations/week"
        )
        stored_season = await get_external_snapshot(
            GUILD_ID, SOURCE_MAJESTIC_API, "rating-organizations/season"
        )
        self.assertIsNotNone(stored_week)
        self.assertIsNotNone(stored_season)
        assert stored_week is not None and stored_season is not None
        self.assertIn("500", stored_week.payload_text)
        self.assertIn("900", stored_season.payload_text)

