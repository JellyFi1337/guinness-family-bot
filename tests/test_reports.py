GUILD_ID = 5_200
FAMILY_ROLE_ID = 76
PERM_ROLE_ID = 77
STAFF_ID = 900
REVIEWER_ID = 901
USER_A = 3_001
USER_B = 3_002


def _role(role_id: int, name: str) -> SimpleNamespace:
    return SimpleNamespace(id=role_id, name=name)


def _guild(roles: list[SimpleNamespace], guild_id: int = GUILD_ID) -> SimpleNamespace:
    by_id = {role.id: role for role in roles}

    def get_role(role_id: int):
        return by_id.get(int(role_id))

    return SimpleNamespace(id=guild_id, roles=roles, get_role=get_role)


def _actor(
    *,
    user_id: int,
    roles: list[SimpleNamespace],
    guild: SimpleNamespace,
    display_name: str = "officer",
) -> SimpleNamespace:
    return SimpleNamespace(
        id=user_id,
        name=display_name,
        display_name=display_name,
        roles=roles,
        guild=guild,
        guild_id=guild.id,
    )


class ReportSchemaTests(unittest.TestCase):
    def test_migration_translates_to_postgresql(self) -> None:
        migration = next(item for item in MIGRATIONS if item.version == 39)
        joined = "\n".join(
            translate_sql(statement, include_returning=False)
            for statement in migration.statements
        )
        self.assertNotIn("AUTOINCREMENT", joined)
        self.assertNotIn("?", joined)
        self.assertIn("BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", joined)
        self.assertIn("idx_report_evidence_hash", joined)


class ReportTests(unittest.IsolatedAsyncioTestCase):
    async def asyncSetUp(self) -> None:
        await database.close_db()
        self.temp_dir = tempfile.TemporaryDirectory()
        self.path_patch = patch.object(
            database,
            "DB_PATH",
            Path(self.temp_dir.name) / "reports.db",
        )
        self.path_patch.start()
        await database.init_db()
        reset_obligation_sources()
        ensure_report_integrations()
        family = _role(FAMILY_ROLE_ID, "High")
        perms = _role(PERM_ROLE_ID, "Кадровик")
        self.guild = _guild([family, perms])
        self.staff = _actor(user_id=STAFF_ID, roles=[family, perms], guild=self.guild)
        self.reviewer = _actor(
            user_id=REVIEWER_ID, roles=[family, perms], guild=self.guild, display_name="R"
        )
        self.alpha = _actor(
            user_id=USER_A, roles=[family], guild=self.guild, display_name="A"
        )
        self.beta = _actor(
            user_id=USER_B, roles=[family], guild=self.guild, display_name="B"
        )
        await grant_role_permission(GUILD_ID, Permission.MEMBERS_MANAGE, PERM_ROLE_ID)
        await grant_role_permission(GUILD_ID, Permission.MEMBERS_VIEW, PERM_ROLE_ID)
        await grant_role_permission(GUILD_ID, Permission.CONTRACTS_MANAGE, PERM_ROLE_ID)
        await grant_role_permission(GUILD_ID, Permission.REPORTS_REVIEW, PERM_ROLE_ID)
        await set_guild_setting(GUILD_ID, "profile.enabled_upgrades", "air_cargo")
        for user_id in (USER_A, USER_B):
            await register_member(
                self.staff, GUILD_ID, discord_id=user_id, ic_name=f"IC{user_id}"
            )
            await verify_in_game(self.staff, GUILD_ID, user_id)

    async def asyncTearDown(self) -> None:
        reset_obligation_sources()
        await database.close_db()
        self.path_patch.stop()
        self.temp_dir.cleanup()

    async def _run(self, *, team_max: int = 2):
        item = await add_catalog_item(
            self.staff,
            GUILD_ID,
            title="Доставка",
            direction="criminal",
            team_max=team_max,
            upgrades="air_cargo",
        )
        published = await change_catalog_status(
            self.staff, GUILD_ID, item.id, "available"
        )
        run = await start_run(self.alpha, GUILD_ID, published.id, share_bps=5000)
        if team_max > 1:
            run = await take_run(self.beta, GUILD_ID, run.id, share_bps=5000)
        return run

    async def test_double_submit_returns_the_same_report(self) -> None:
        run = await self._run()
        first = await submit_report(
            self.alpha,
            GUILD_ID,
            run.id,
            result_amount=100,
            shares=f"{USER_A}:60,{USER_B}:40",
            duration_minutes=30,
            links="https://example.com/a.png",
        )
        second = await submit_report(
            self.alpha,
            GUILD_ID,
            run.id,
            result_amount=999,
            shares=f"{USER_A}:999",
            duration_minutes=1,
            links="https://example.com/b.png",
        )
        self.assertEqual(first.id, second.id)
        self.assertEqual(second.result_amount, 100)
        stored = await get_run(run.id)
        assert stored is not None
        self.assertEqual(stored.status, "report_submitted")

    async def test_parallel_accept_creates_one_obligation(self) -> None:
        run = await self._run()
        report = await submit_report(
            self.alpha,
            GUILD_ID,
            run.id,
            result_amount=80,
            shares=f"{USER_A}:40,{USER_B}:40",
            duration_minutes=20,
            links="https://example.com/shot.png",
        )

        async def _accept(actor: SimpleNamespace) -> str:
            try:
                accepted = await review_report(
                    actor, GUILD_ID, report.id, "accept", reason="проверка"
                )
                return f"ok:{accepted.obligation.id if accepted.obligation else 0}"
            except ReportError as exc:
                return exc.code

        first, second = await asyncio.gather(
            _accept(self.staff), _accept(self.reviewer)
        )
        self.assertTrue(first.startswith("ok:") or second.startswith("ok:"))
        codes = {first, second}
        self.assertTrue(
            any(item.startswith("ok:") for item in codes)
        )
        leftovers = {item for item in codes if not item.startswith("ok:")}
        self.assertTrue(not leftovers or leftovers <= {"REPORTS.CONFLICT", "REPORTS.ALREADY_REVIEWED"})
        stored = await get_report(report.id)
        assert stored is not None
        self.assertEqual(stored.status, "accepted")
        assert stored.obligation is not None
        self.assertEqual(stored.obligation.status, "open")
        self.assertEqual(stored.obligation.amount, 80)

    async def test_author_cannot_accept_own_report(self) -> None:
        run = await self._run(team_max=1)
        report = await submit_report(
            self.alpha,
            GUILD_ID,
            run.id,
            result_amount=10,
            shares=f"{USER_A}:10",
            duration_minutes=5,
            links="https://example.com/own.png",
        )
        staff_as_author = _actor(
            user_id=USER_A, roles=self.staff.roles, guild=self.guild
        )
        await grant_role_permission(GUILD_ID, Permission.REPORTS_REVIEW, FAMILY_ROLE_ID)
        with self.assertRaises(ReportError) as raised:
            await review_report(
                staff_as_author, GUILD_ID, report.id, "accept", reason="сам"
            )
        self.assertEqual(raised.exception.code, "REPORTS.SELF_REVIEW")
        stored = await get_report(report.id)
        assert stored is not None
        self.assertEqual(stored.status, "submitted")
        self.assertIsNone(stored.obligation)

    async def test_reverse_keeps_numbers_and_writes_audit(self) -> None:
        run = await self._run(team_max=1)
        report = await submit_report(
            self.alpha,
            GUILD_ID,
            run.id,
            result_amount=25,
            shares=f"{USER_A}:25",
            duration_minutes=15,
            links="https://example.com/ok.png",
        )
        accepted = await review_report(
            self.staff, GUILD_ID, report.id, "accept", reason="принято"
        )
        reversed_report = await reverse_report(
            self.reviewer, GUILD_ID, accepted.id, reason="ошибка сверки"
        )
        self.assertEqual(reversed_report.status, "reversed")
        self.assertEqual(reversed_report.result_amount, 25)
        self.assertEqual(reversed_report.shares[0].amount, 25)
        assert reversed_report.obligation is not None
        self.assertEqual(reversed_report.obligation.status, "cancelled")
        self.assertEqual(len(reversed_report.reversals), 1)
        decisions = await list_decisions(
            GUILD_ID, subject_type="contract_report", subject_id=str(report.id)
        )
        actions = [row.action for row in decisions]
        self.assertIn("REPORTS.SUBMIT", actions)
        self.assertIn("REPORTS.ACCEPT", actions)
        self.assertIn("REPORTS.REVERSE", actions)

    async def test_group_shares_must_equal_result(self) -> None:
        run = await self._run()
        with self.assertRaises(ReportError) as raised:
            await submit_report(
                self.alpha,
                GUILD_ID,
                run.id,
                result_amount=100,
                shares=f"{USER_A}:60,{USER_B}:30",
                duration_minutes=10,
                links="https://example.com/x.png",
            )
        self.assertEqual(raised.exception.code, "REPORTS.SHARE_SUM")
        ok = await submit_report(
            self.alpha,
            GUILD_ID,
            run.id,
            result_amount=100,
            shares=f"{USER_A}:60,{USER_B}:40",
            duration_minutes=10,
            links="https://example.com/x.png",
        )
        self.assertEqual(sum(item.amount for item in ok.shares), 100)

    async def test_duplicate_evidence_is_flagged(self) -> None:
        first_run = await self._run(team_max=1)
        payload = b"same-bytes"
        first = await submit_report(
            self.alpha,
            GUILD_ID,
            first_run.id,
            result_amount=5,
            shares=f"{USER_A}:5",
            duration_minutes=3,
            attachments=(EvidenceDraft("attachment", payload, url=None),),
        )
        await review_report(self.staff, GUILD_ID, first.id, "accept", reason="ок")
        item = await add_catalog_item(
            self.staff,
            GUILD_ID,
            title="Второй",
            direction="criminal",
            team_max=1,
            upgrades="air_cargo",
        )
        published = await change_catalog_status(
            self.staff, GUILD_ID, item.id, "available"
        )
        second_run = await start_run(self.beta, GUILD_ID, published.id)
        second = await submit_report(
            self.beta,
            GUILD_ID,
            second_run.id,
            result_amount=5,
            shares=f"{USER_B}:5",
            duration_minutes=3,
            attachments=(EvidenceDraft("attachment", payload, url=None),),
        )
        self.assertEqual(second.evidence[0].duplicate_report_ids, (first.id,))

