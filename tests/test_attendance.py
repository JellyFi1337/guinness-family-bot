GUILD_ID = 6_200
FAMILY_ROLE_ID = 86
PERM_ROLE_ID = 87
STAFF_ID = 2_010
USER_A = 6_001
USER_B = 6_002


def _role(role_id: int, name: str) -> SimpleNamespace:
    return SimpleNamespace(id=role_id, name=name)


def _guild(roles: list[SimpleNamespace], guild_id: int = GUILD_ID) -> SimpleNamespace:
    by_id = {role.id: role for role in roles}

    def get_role(role_id: int):
        return by_id.get(int(role_id))

    return SimpleNamespace(id=guild_id, roles=roles, get_role=get_role, members=[])


def _actor(
    *,
    user_id: int,
    roles: list[SimpleNamespace],
    guild: SimpleNamespace,
    display_name: str = "officer",
) -> SimpleNamespace:
    return SimpleNamespace(
        id=user_id,
        name=display_name,
        display_name=display_name,
        roles=roles,
        guild=guild,
        guild_id=guild.id,
    )


def _window(hours: int = 2, duration: int = 2) -> tuple[str, str]:
    start = datetime.now(UTC) + timedelta(hours=hours)
    end = start + timedelta(hours=duration)
    return start.isoformat(), end.isoformat()


class AttendanceSchemaTests(unittest.TestCase):
    def test_migration_translates_to_postgresql(self) -> None:
        migration = next(item for item in MIGRATIONS if item.version == 43)
        joined = "\n".join(
            translate_sql(statement, include_returning=False)
            for statement in migration.statements
        )
        self.assertNotIn("AUTOINCREMENT", joined)
        self.assertNotIn("?", joined)
        self.assertIn("event_attendance_log", joined)
        self.assertIn("BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", joined)


class AttendanceTests(unittest.IsolatedAsyncioTestCase):
    async def asyncSetUp(self) -> None:
        await database.close_db()
        self.temp_dir = tempfile.TemporaryDirectory()
        self.path_patch = patch.object(
            database,
            "DB_PATH",
            Path(self.temp_dir.name) / "attendance.db",
        )
        self.path_patch.start()
        await database.init_db()
        reset_obligation_sources()
        reset_leftover_actions()
        ensure_event_integrations()
        family = _role(FAMILY_ROLE_ID, "High")
        perms = _role(PERM_ROLE_ID, "Кадровик")
        self.guild = _guild([family, perms])
        self.staff = _actor(user_id=STAFF_ID, roles=[family, perms], guild=self.guild)
        self.alpha = _actor(
            user_id=USER_A, roles=[family], guild=self.guild, display_name="A"
        )
        self.beta = _actor(
            user_id=USER_B, roles=[family], guild=self.guild, display_name="B"
        )
        for permission in (
            Permission.MEMBERS_MANAGE,
            Permission.MEMBERS_VIEW,
            Permission.EVENTS_CREATE,
            Permission.EVENTS_MANAGE_OWN,
            Permission.EVENTS_MANAGE_ALL,
        ):
            await grant_role_permission(GUILD_ID, permission, PERM_ROLE_ID)
        await register_member(
            self.staff, GUILD_ID, discord_id=STAFF_ID, ic_name="Staff"
        )
        for user_id in (USER_A, USER_B):
            await register_member(
                self.staff, GUILD_ID, discord_id=user_id, ic_name=f"IC{user_id}"
            )
            await verify_in_game(self.staff, GUILD_ID, user_id)

    async def asyncTearDown(self) -> None:
        reset_obligation_sources()
        reset_leftover_actions()
        await database.close_db()
        self.path_patch.stop()
        self.temp_dir.cleanup()

    async def _meeting(self, *, capacity: int = 1, reserve: int = 1) -> object:
        start, end = _window()
        return await create_event(
            self.staff,
            GUILD_ID,
            "meeting",
            starts_at=start,
            ends_at=end,
            meetup="офис организации",
            capacity=capacity,
            reserve_capacity=reserve,
            commander_id=USER_A,
        )

    async def test_last_seat_race_has_one_main(self) -> None:
        event = await self._meeting(capacity=1, reserve=1)
        first, second = await asyncio.gather(
            join_event(self.alpha, GUILD_ID, event.id),
            join_event(self.beta, GUILD_ID, event.id),
        )
        slots = {first.seat.slot, second.seat.slot}
        self.assertEqual(slots, {"main", "reserve"})
        self.assertEqual({first.seat.discord_id, second.seat.discord_id}, {USER_A, USER_B})
        roster = await list_roster(event.id)
        self.assertEqual(len(roster), 2)
        self.assertEqual(sum(1 for seat in roster if seat.slot == "main"), 1)

    async def test_join_is_idempotent_and_not_both_slots(self) -> None:
        event = await self._meeting(capacity=2, reserve=2)
        one = await join_event(self.alpha, GUILD_ID, event.id)
        two = await join_event(self.alpha, GUILD_ID, event.id)
        self.assertEqual(one.seat.id, two.seat.id)
        self.assertEqual(one.seat.slot, "main")
        seats = [seat for seat in await list_roster(event.id) if seat.discord_id == USER_A]
        self.assertEqual(len(seats), 1)

    async def test_reserve_promotes_before_lock(self) -> None:
        event = await self._meeting(capacity=1, reserve=1)
        await join_event(self.alpha, GUILD_ID, event.id)
        reserved = await join_event(self.beta, GUILD_ID, event.id)
        self.assertEqual(reserved.seat.slot, "reserve")
        queue = await reserve_queue(event)
        self.assertEqual(queue[0].position, 1)
        self.assertEqual(queue[0].basis, "время записи")
        result = await leave_event(self.alpha, GUILD_ID, event.id)
        self.assertIsNotNone(result.promoted)
        assert result.promoted is not None
        self.assertEqual(result.promoted.discord_id, USER_B)
        self.assertEqual(result.promoted.slot, "main")
        self.assertEqual(result.promoted.attendance, "joined")
        leftover = await promote_reserve_leftover(
            self.staff, GUILD_ID, f"{event.id}:{USER_B}"
        )
        self.assertIn("некого", leftover.casefold())

    async def test_cancelled_event_excluded_from_stats(self) -> None:
        event = await self._meeting(capacity=2, reserve=0)
        await join_event(self.alpha, GUILD_ID, event.id)
        await confirm_attendance(self.alpha, GUILD_ID, event.id, USER_A, "no_show")
        await cancel_event(self.staff, GUILD_ID, event.id)
        stats = await attendance_stats(self.staff, GUILD_ID, USER_A)
        self.assertEqual(stats.cancelled_excluded, 1)
        self.assertEqual(stats.no_show, 0)
        self.assertEqual(stats.obligated, 0)

    async def test_excuse_and_leave_excluded_from_stats(self) -> None:
        first = await self._meeting(capacity=2, reserve=0)
        await join_event(self.alpha, GUILD_ID, first.id)
        await excuse_member(self.staff, GUILD_ID, first.id, USER_A, "согласовано")
        second_start, second_end = _window(hours=6)
        second = await create_event(
            self.staff,
            GUILD_ID,
            "training",
            starts_at=second_start,
            ends_at=second_end,
            meetup="офис организации",
            capacity=2,
            commander_id=USER_A,
        )
        await join_event(self.beta, GUILD_ID, second.id)
        member = await get_current_member(second.family_id, USER_B)
        assert member is not None
        await mark_leave(
            member.id, actor_id=STAFF_ID, actor_name="Staff", reason="отпуск"
        )
        excused = await attendance_stats(self.staff, GUILD_ID, USER_A)
        self.assertEqual(excused.excused_excluded, 1)
        self.assertEqual(excused.obligated, 0)
        on_leave = await attendance_stats(self.staff, GUILD_ID, USER_B)
        self.assertEqual(on_leave.leave_excluded, 1)
        self.assertEqual(on_leave.obligated, 0)

    async def test_attendance_requires_this_event_commander(self) -> None:
        event = await self._meeting(capacity=2, reserve=0)
        await join_event(self.alpha, GUILD_ID, event.id)
        with self.assertRaises(EventError) as raised:
            await confirm_attendance(self.staff, GUILD_ID, event.id, USER_A, "attended")
        self.assertEqual(raised.exception.code, "EVENTS.NOT_COMMANDER")
        with self.assertRaises(EventError) as other:
            await confirm_attendance(self.beta, GUILD_ID, event.id, USER_A, "attended")
        self.assertEqual(other.exception.code, "EVENTS.NOT_COMMANDER")
        marked = await confirm_attendance(
            self.alpha, GUILD_ID, event.id, USER_A, "attended"
        )
        self.assertEqual(marked.attendance, "attended")
        again = await confirm_attendance(
            self.alpha, GUILD_ID, event.id, USER_A, "attended"
        )
        self.assertEqual(again.attendance, "attended")
        log = await list_attendance_log(event.id, USER_A)
        self.assertGreaterEqual(len(log), 2)
        self.assertEqual(log[-1].actor_id, USER_A)
        stats = await attendance_stats(self.staff, GUILD_ID, USER_A)
        self.assertEqual(stats.attended, 1)
        self.assertEqual(stats.obligated, 1)

    async def test_lock_blocks_auto_promote_and_replace_notifies(self) -> None:
        event = await self._meeting(capacity=1, reserve=1)
        await join_event(self.alpha, GUILD_ID, event.id)
        await join_event(self.beta, GUILD_ID, event.id)
        locked = await lock_roster(self.staff, GUILD_ID, event.id)
        self.assertTrue(locked.roster_locked)
        with self.assertRaises(EventError) as raised:
            await leave_event(self.alpha, GUILD_ID, event.id)
        self.assertEqual(raised.exception.code, "EVENTS.LOCKED")
        leftover = await dispatch_leftover_action(
            self.staff, GUILD_ID, action="promote_reserve", subject_id=str(event.id)
        )
        self.assertIn("зафиксирован", leftover.casefold())
        outgoing, incoming = await replace_after_lock(
            self.staff,
            GUILD_ID,
            event.id,
            USER_A,
            USER_B,
            "не сможет выйти",
        )
        self.assertEqual(outgoing.slot, "reserve")
        self.assertEqual(incoming.slot, "main")
        self.assertEqual(incoming.discord_id, USER_B)
        async with connection() as db:
            rows = await db.execute_fetchall(
                "SELECT kind FROM operation_outbox WHERE kind = ?",
                ("event.reserve_replace",),
            )
        self.assertEqual(len(rows), 1)

    async def test_ready_and_voice_do_not_prove_attendance(self) -> None:
        event = await self._meeting(capacity=2, reserve=0)
        await join_event(self.alpha, GUILD_ID, event.id)
        ready = await confirm_ready(self.alpha, GUILD_ID, event.id)
        self.assertEqual(ready.attendance, "ready")
        hinted = await mark_voice_hint(self.staff, GUILD_ID, event.id, USER_A)
        self.assertIsNotNone(hinted.voice_seen_at)
        self.assertEqual(hinted.attendance, "ready")
        stats = await attendance_stats(self.staff, GUILD_ID, USER_A)
        self.assertEqual(stats.attended, 0)
        self.assertEqual(stats.pending, 1)

    async def test_texts_avoid_vzp(self) -> None:
        event = await self._meeting()
        await join_event(self.alpha, GUILD_ID, event.id)
        log = await list_attendance_log(event.id)
        blob = " ".join(item.reason or "" for item in log).casefold()
        self.assertNotIn("vzp", blob)
        self.assertNotIn("взп", blob)
