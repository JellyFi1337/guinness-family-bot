    async def test_return_is_not_consume(self) -> None:
        await self._sku()
        await receive_stock(self.staff, GUILD_ID, sku="ammo", quantity=10)
        event = await self._event()
        kit = await request_kit(
            self.alpha, GUILD_ID, event_id=event.id, sku="ammo", quantity=10
        )
        await reserve_kit(self.staff, GUILD_ID, kit.id)
        await issue_kit(self.staff, GUILD_ID, kit.id)
        warehouse_after_issue = await self._balance("ammo")
        assert warehouse_after_issue is not None
        self.assertEqual(warehouse_after_issue.on_hand, 0)
        await return_kit_item(
            self.staff, GUILD_ID, kit_id=kit.id, sku="ammo", quantity=4
        )
        after_return = await self._balance("ammo")
        handout = await self._balance("ammo", "handout")
        assert after_return is not None
        assert handout is not None
        self.assertEqual(after_return.on_hand, 4)
        self.assertEqual(handout.on_hand, 6)
        await consume_kit_item(
            self.staff, GUILD_ID, kit_id=kit.id, sku="ammo", quantity=3
        )
        after_consume = await self._balance("ammo")
        handout_after = await self._balance("ammo", "handout")
        assert after_consume is not None
        assert handout_after is not None
        self.assertEqual(after_consume.on_hand, 4)
        self.assertEqual(handout_after.on_hand, 3)

